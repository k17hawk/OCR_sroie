"""Generate the schema files from the Pydantic models (one source of truth).

    python -m scripts.gen_schema            # write
    python -m scripts.gen_schema --check    # exit 1 if a checked-in file is stale

Writes (paths relative to the repo root):
    schema/doc_v2.schema.json       legacy v2, still used by the app until the switch-over
    schema/doc_v21.schema.json      schema 2.1
    ocr/frontend/src/schema.gen.ts  TypeScript types for 2.1 (json-schema-to-typescript)

The TS step needs ``pnpm install`` in ocr/frontend once.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

from app.schemas import doc_v2, doc_v21

REPO = Path(__file__).resolve().parents[3]
FRONTEND = REPO / "ocr" / "frontend"
TS_OUT = FRONTEND / "src" / "schema.gen.ts"
TS_BANNER = (
    "/* eslint-disable */\n"
    "// GENERATED by `python -m scripts.gen_schema` from app/schemas/doc_v21.py.\n"
    "// Do not edit by hand.\n"
)


def _json(model) -> str:
    return json.dumps(model.model_json_schema(), indent=2, ensure_ascii=False) + "\n"


def _strip_property_titles(node):
    """json2ts turns every property ``title`` into a named alias (Id26, Text26…);
    only model titles (under $defs / the root) should become type names."""
    if isinstance(node, dict):
        props = node.get("properties")
        if isinstance(props, dict):
            for p in props.values():
                if isinstance(p, dict):
                    p.pop("title", None)
        for v in node.values():
            _strip_property_titles(v)
    elif isinstance(node, list):
        for v in node:
            _strip_property_titles(v)
    return node


def _ts(schema_text: str) -> str:
    json2ts = FRONTEND / "node_modules" / ".bin" / "json2ts"
    if not json2ts.exists():
        raise SystemExit(f"{json2ts} missing: run `pnpm install` in {FRONTEND}")
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / "doc_v21.schema.json"
        src.write_text(json.dumps(_strip_property_titles(json.loads(schema_text))),
                       encoding="utf-8")
        out = subprocess.run(
            [str(json2ts), "-i", str(src), "--no-bannerComment", "--unreachableDefinitions",
             "--additionalProperties", "false"],
            check=True, capture_output=True, text=True,
        ).stdout
    return TS_BANNER + f'export const SCHEMA_VERSION = "{doc_v21.SCHEMA_VERSION}";\n\n' + out


def outputs() -> dict[Path, str]:
    v21 = _json(doc_v21.Doc)
    return {
        REPO / "schema" / "doc_v2.schema.json": _json(doc_v2.Doc),
        REPO / "schema" / "doc_v21.schema.json": v21,
        TS_OUT: _ts(v21),
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if files are out of date")
    args = ap.parse_args(argv)
    stale = []
    for path, text in outputs().items():
        rel = path.relative_to(REPO)
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if args.check:
            if current != text:
                stale.append(str(rel))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {rel}")
    if stale:
        print("out of date (run python -m scripts.gen_schema):\n  " + "\n  ".join(stale))
        return 1
    if args.check:
        print("schema files up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
