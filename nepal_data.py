# --------------------------------------------------------------------------------------
# Consistent sampling helpers (use these in the generator so district, local level and ward always agree)
# --------------------------------------------------------------------------------------
import random as _random

_DEV_DIGITS = str.maketrans("0123456789", "०१२३४५६७८९")


def to_dev_digits(s) -> str:
    return str(s).translate(_DEV_DIGITS)


def sample_address(rng: "_random.Random" = _random) -> dict:
    """A real local level with its own district, province and a valid ward number (1..wards)."""
    name, kind, district, wards = rng.choice(LOCAL_LEVELS)
    return {"province": DISTRICTS[district], "district": district, "local_level": name, "local_type": kind,
            "ward": rng.randint(1, wards)}


def sample_person(rng: "_random.Random" = _random, female: bool = None) -> str:
    female = rng.random() < 0.5 if female is None else female
    first = rng.choice(FEMALE_NAMES if female else MALE_NAMES)
    parts = [first]
    if rng.random() < 0.35:
        parts.append(rng.choice(FEMALE_MIDDLE if female else MALE_MIDDLE))
    names, weights = zip(*SURNAMES.items())
    parts.append(rng.choices(names, weights)[0])
    return " ".join(parts)


def sample_bs_date(rng: "_random.Random" = _random, years=(2070, 2090)) -> tuple:
    """Valid Bikram Sambat (year, month, day) within the table range."""
    y = rng.randint(years[0], years[1])
    m = rng.randint(1, 12)
    d = rng.randint(1, BS_MONTH_DAYS[y][m - 1])
    return y, m, d
